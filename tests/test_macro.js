"use strict";
const assert=require("node:assert/strict");
const {isSensitive,isSensitiveValue,validateStep,cleanSteps}=require("../macro.js");
const input=(type,field,autocomplete="")=>({type,name:field,id:field,autocomplete,dataset:{field}});
assert.equal(isSensitive(input("text","work-code")),false);
assert.equal(isSensitive(input("email","contact-email","email")),true);
assert.equal(isSensitive(input("password","demo-password","current-password")),true);
assert.equal(isSensitive(input("text","api-key")),true);
assert.equal(isSensitiveValue("WO-204"),false);
assert.equal(isSensitiveValue("person@example.test"),true);
assert.equal(isSensitiveValue("555-123-4567"),true);
assert.equal(isSensitiveValue("sk-live_verysecretkey123"),true);
const good={id:"s1",type:"input",target:"crm-demo",field:"work-code",value:"WO-204"};
assert.equal(validateStep(good),true);
assert.equal(validateStep({...good,target:"other"}),false);
assert.equal(validateStep({...good,field:"contact-email"}),false);
assert.equal(validateStep({...good,value:"person@example.test"}),false);
assert.equal(validateStep({...good,value:"x".repeat(241)}),false);
assert.equal(validateStep({type:"click",target:"crm-demo",action:"add-item"}),true);
assert.equal(validateStep({type:"click",target:"crm-demo",action:"mark-ready",key:"WO-204"}),true);
assert.equal(validateStep({type:"click",target:"crm-demo",action:"mark-ready"}),false);
assert.equal(validateStep({type:"click",target:"crm-demo",action:"submit-form"}),false);
assert.equal(validateStep({type:"wait",target:"crm-demo",value:750}),true);
assert.equal(validateStep({type:"wait",target:"crm-demo",value:30001}),false);
assert.equal(validateStep({type:"scroll",target:"crm-demo",value:120}),true);
assert.equal(validateStep({type:"scroll",target:"crm-demo",value:10001}),false);
const cleaned=cleanSteps([good,{...good,id:"s2",value:"person@example.test"},{...good,id:"s3",target:"outside"}]);
assert.deepEqual(cleaned.map(x=>x.id),["s1"]);
assert.equal(cleanSteps(Array.from({length:140},(_,i)=>({...good,id:String(i)}))).length,120);
console.log("22 macro safety assertions passed");
